def medicine_category(atc: str | None) -> str:
    """ATC → θεραπευτική κατηγορία φαρμάκου (auto). Άγνωστο/κενό → «Διάφορα / Λοιπά»."""
    a = (atc or "").upper().strip()
    if not a:
        return "Διάφορα / Λοιπά"
    if a[:3] in _ATC_SPECIFIC:
        return _ATC_SPECIFIC[a[:3]]
    return _ATC_ANATOMICAL.get(a[:1], "Διάφορα / Λοιπά")


