UNKNOWN = {"key": "—", "short": "Χωρίς κατάταξη", "name": "Χωρίς κατάταξη", "range": ""}


def chapter_for(code: str) -> dict:
    """→ {key, short, name, range} για έναν κωδικό ICD-10. Ποτέ δεν σκάει σε σκουπίδια."""
    c = str(code or "").strip().upper().replace(".", "")
    if len(c) < 3 or not c[0].isalpha() or not c[1:3].isdigit():
        return dict(UNKNOWN)
    letter, num = c[0], int(c[1:3])
    for a_l, a_n, b_l, b_n, short, name in _CHAPTERS:
        # Το εύρος είναι λεξικογραφικό πάνω στο (γράμμα, αριθμός) — π.χ. S00–T98.
        if (a_l, a_n) <= (letter, num) <= (b_l, b_n):
            rng = f"{a_l}{a_n:02d}-{b_l}{b_n:02d}"
            return {"key": rng, "short": short, "name": name, "range": rng}
    return dict(UNKNOWN)


def chapters() -> list[dict]:
    return [{"key": f"{a}{an:02d}-{b}{bn:02d}", "short": s, "name": n,
             "range": f"{a}{an:02d}-{b}{bn:02d}"} for a, an, b, bn, s, n in _CHAPTERS]
