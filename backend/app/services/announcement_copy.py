def copy_for(addon: dict | None) -> dict:
    """Έτοιμο κείμενο για ένα add-on.

    Αν δεν υπάρχει γραμμένο, φτιάχνεται ΑΞΙΟΠΡΕΠΕΣ προσχέδιο από τον κατάλογο (όνομα/περιγραφή/
    δυνατότητες) — ώστε κάθε νέο add-on να έχει κάτι χρησιμοποιήσιμο από την πρώτη μέρα, χωρίς
    να χρειάζεται να γραφτεί κώδικας. Ο τίτλος μένει ουδέτερος επίτηδες: καλύτερα «Νέο: Χ» παρά
    ένας φτιαχτός γάντζος που δεν ταιριάζει στο κύκλωμα.
    """
    key = (addon or {}).get("_id")
